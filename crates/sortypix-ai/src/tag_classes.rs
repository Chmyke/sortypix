#[cfg(test)]
mod tests {
    use super::*;
    use crate::vocabulary::find;
    use std::collections::HashSet;

    #[test]
    fn every_entry_names_a_word_once_and_real_classes() {
        let mut seen = HashSet::new();
        for (word, classes) in CLASSES {
            assert!(find(word).is_some(), "{word} is not in the vocabulary");
            assert!(seen.insert(*word), "{word} twice");
            assert!(!classes.is_empty(), "{word} without classes");
            for (id, name) in *classes {
                assert!(
                    id.starts_with("/m/") || id.starts_with("/g/"),
                    "{word}: {id}"
                );
                assert!(!name.is_empty());
            }
        }
    }
}
