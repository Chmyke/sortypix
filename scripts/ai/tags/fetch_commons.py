"""Fetches generated and drawn images for the tag sets from Wikimedia Commons (development).

Images go to <ai-dev>/<set>/generated/ (tags-test: held out; tags-tuning: tuning, drawn with
another seed and without the titles of the held-out manifest) with manifest.json (title, page, license, author,
bucket). Only free licenses are kept (CC0, public domain, CC BY, CC BY-SA); the images never
enter the repository. Each bucket takes up to --per images, drawn at random (fixed seed) from its
categories (files directly in them and in their subcategories, one level down). Polite: one
request at a time, a pause between requests, Retry-After honoured.

python -I scripts/ai/tags/fetch_commons.py [--dir <ai-dev>] [--per 12]
"""
import argparse
import json
import os
import random
import time
import urllib.error
import urllib.parse
import urllib.request

API = "https://commons.wikimedia.org/w/api.php"
AGENT = "SortypixDev/0.4 (open-source photo sorter; one-off test set build)"
BUCKETS = {
    "anime": ["AI-generated anime illustrations", "AI-generated anime", "Anime illustrations", "AI-generated manga illustrations"],
    "3d render": ["Rendered with Sheepit", "Lighting design in residential buildings, Blender renders", "POV-Ray", "Blender (software)"],
    "digital art": ["Digital painting", "Digital art", "AI-generated images by artstyle"],
    "painting": ["AI-generated paintings", "Watercolor paintings"],
    "pixel art": ["Pixel art", "AI-generated pixel art"],
    "photorealistic ai": ["Images generated by Stable Diffusion by subject", "Stable Diffusion works by Commons users"],
    "comic": ["AI-generated comics illustrations", "AI-generated comic strips"],
    "screenshot": ["Screenshots of free software", "Screenshots of software"],
}
FREE = ("cc0", "public domain", "pd", "cc by", "cc-by")
BLOCK = ("nude", "nudity", "erotic", "sex", "naked", "nsfw", "breast", "lingerie")


def call(params):
    params = {**params, "format": "json"}
    url = API + "?" + urllib.parse.urlencode(params)
    for attempt in range(6):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": AGENT})
            with urllib.request.urlopen(req, timeout=30) as r:
                time.sleep(1.0)
                return json.load(r)
        except urllib.error.HTTPError as e:
            wait = int(e.headers.get("Retry-After", "10")) if e.code == 429 else 5
            time.sleep(wait + 1)
    raise RuntimeError("Commons API unavailable")


def members(category, kind):
    out, cont = [], {}
    while True:
        r = call({"action": "query", "list": "categorymembers", "cmtitle": "Category:" + category,
                  "cmtype": kind, "cmlimit": 500, **cont})
        out += [m["title"] for m in r.get("query", {}).get("categorymembers", [])]
        if "continue" not in r or len(out) >= 1500:
            return out
        cont = r["continue"]


def files_of(category):
    files = members(category, "file")
    for sub in members(category, "subcat")[:20]:
        files += members(sub[len("Category:"):], "file")
    return [f for f in files if f.lower().endswith((".jpg", ".jpeg", ".png"))]


def info(titles):
    r = call({"action": "query", "titles": "|".join(titles), "prop": "imageinfo|categories",
              "iiprop": "url|extmetadata", "iiurlwidth": 640, "cllimit": 50})
    return list(r.get("query", {}).get("pages", {}).values())


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--dir", default=os.path.join(os.environ.get("LOCALAPPDATA", ""), "Sortypix", "ai-dev"))
    p.add_argument("--per", type=int, default=12)
    p.add_argument("--set", default="tags-test", help="tags-test (held out) or tags-tuning")
    p.add_argument("--seed", type=int, default=7)
    p.add_argument("--exclude", help="manifest.json whose titles are skipped (keeps the sets apart)")
    a = p.parse_args()
    out = os.path.join(a.dir, a.set, "generated")
    excluded = set()
    if a.exclude:
        excluded = {m["title"] for m in json.load(open(a.exclude))}
    os.makedirs(out, exist_ok=True)
    rng = random.Random(a.seed)
    manifest = []
    for bucket, categories in BUCKETS.items():
        candidates = sorted({f for c in categories for f in files_of(c)})
        rng.shuffle(candidates)
        kept = 0
        for i in range(0, len(candidates), 20):
            if kept >= a.per:
                break
            for page in info(candidates[i:i + 20]):
                if kept >= a.per or "imageinfo" not in page or page["title"] in excluded:
                    continue
                ii = page["imageinfo"][0]
                meta = ii.get("extmetadata", {})
                lic = meta.get("LicenseShortName", {}).get("value", "")
                cats = " ".join(c["title"].lower() for c in page.get("categories", []))
                if not lic.lower().startswith(FREE) or any(b in cats or b in page["title"].lower() for b in BLOCK):
                    continue
                if "nc" in lic.lower().replace("-", " ").split():
                    continue
                ext = os.path.splitext(urllib.parse.urlparse(ii["thumburl"]).path)[1].lower()
                name = "%s-%02d%s" % (bucket.replace(" ", "-"), kept + 1, ext if ext in (".jpg", ".jpeg", ".png") else ".jpg")
                req = urllib.request.Request(ii["thumburl"], headers={"User-Agent": AGENT})
                try:
                    with urllib.request.urlopen(req, timeout=60) as r:
                        data = r.read()
                except urllib.error.URLError:
                    continue
                time.sleep(1.0)
                with open(os.path.join(out, name), "wb") as f:
                    f.write(data)
                manifest.append({"file": name, "bucket": bucket, "title": page["title"], "page": ii.get("descriptionurl"),
                                 "license": lic, "author": meta.get("Artist", {}).get("value", "")[:200]})
                kept += 1
        print(bucket, kept, "of", len(candidates), "candidates", flush=True)
    json.dump(manifest, open(os.path.join(out, "manifest.json"), "w"), indent=1)


if __name__ == "__main__":
    main()
